import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dest=path.join(root,'desktop/build');
await fs.rm(dest,{recursive:true,force:true});
await fs.mkdir(dest,{recursive:true});
await build({entryPoints:[path.join(root,'desktop/main.cjs')],outfile:path.join(dest,'workbench.cjs'),bundle:true,platform:'node',format:'cjs',external:['electron'],target:'node22'});
await fs.writeFile(path.join(dest,'main.cjs'),"'use strict';\nif(process.argv.includes('--huikan-companion'))require('./companion/src/main.js');else require('./workbench.cjs');\n");
await fs.copyFile(path.join(root,'desktop/preload.cjs'),path.join(dest,'preload.cjs'));
await fs.cp(path.join(root,'ui/dist'),path.join(dest,'renderer'),{recursive:true});
await fs.cp(path.join(root,'companion'),path.join(dest,'companion'),{recursive:true,filter:value=>!value.includes('node_modules')&&!value.includes('.local')});
await fs.cp(path.join(root,'shared'),path.join(dest,'shared'),{recursive:true});
await fs.mkdir(path.join(dest,'plugin'),{recursive:true});
await fs.copyFile(path.join(root,'harness-plugin/packages/mengcang-harness-recall-0.2.0.tgz'),path.join(dest,'plugin/mengcang-harness-recall-0.2.0.tgz'));
await fs.writeFile(path.join(dest,'package.json'),JSON.stringify({name:'recall-workbench-only',version:'0.2.0',main:'main.cjs',private:true}));
console.log('回看工作台已构建。');
