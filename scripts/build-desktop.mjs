import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const codexEnabled=process.env.HUIKAN_ENABLE_CODEX==='1';
const define={__HUIKAN_CODEX_ENABLED__:JSON.stringify(codexEnabled),'process.env.HUIKAN_ENABLE_CODEX':JSON.stringify(codexEnabled?'1':'0')};
if(codexEnabled)await import('../codex-plugin/scripts/build.mjs');
const {version}=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const pluginVersion=JSON.parse(await fs.readFile(path.join(root,'harness-plugin/package.json'),'utf8')).version;
const dest=path.join(root,'desktop/build');
await fs.rm(dest,{recursive:true,force:true});
await fs.mkdir(dest,{recursive:true});
if(process.platform==='darwin')execFileSync('/usr/bin/swiftc',['-O','-module-cache-path',path.join(os.tmpdir(),'huikan-swift-module-cache'),path.join(root,'scripts/mac-shortcut-probe.swift'),'-o',path.join(dest,'mac-shortcut-probe')],{stdio:'inherit'});
for(const file of ['LICENSE','THIRD_PARTY_NOTICES.md'])await fs.copyFile(path.join(root,file),path.join(dest,file));
await build({entryPoints:[path.join(root,'desktop/main.cjs')],outfile:path.join(dest,'workbench.cjs'),bundle:true,platform:'node',format:'cjs',external:['electron','original-fs'],target:'node22',define,minifySyntax:true});
await fs.writeFile(path.join(dest,'main.cjs'),"'use strict';\nif(process.argv.includes('--huikan-companion'))require('./companion/src/main.js');else require('./workbench.cjs');\n");
if(codexEnabled)await fs.copyFile(path.join(root,'codex-plugin/dist/server.cjs'),path.join(dest,'codex-mcp.cjs'));
await build({entryPoints:[path.join(root,'desktop/preload.cjs')],outfile:path.join(dest,'preload.cjs'),bundle:true,platform:'node',format:'cjs',external:['electron'],target:'node22',define,minifySyntax:true});
await fs.cp(path.join(root,'ui/dist'),path.join(dest,'renderer'),{recursive:true});
await fs.cp(path.join(root,'companion'),path.join(dest,'companion'),{recursive:true,filter:value=>!value.includes('node_modules')&&!value.includes('.local')});
await fs.cp(path.join(root,'shared'),path.join(dest,'shared'),{recursive:true});
await fs.writeFile(path.join(dest,'shared/integrations.cjs'),`'use strict';\nmodule.exports=Object.freeze({codexEnabled:${codexEnabled}});\n`);
await fs.mkdir(path.join(dest,'plugin'),{recursive:true});
await fs.copyFile(path.join(root,`harness-plugin/packages/mengcang-harness-recall-${pluginVersion}.tgz`),path.join(dest,'plugin/recall-plugin.tgz'));
await fs.writeFile(path.join(dest,'package.json'),JSON.stringify({name:'huikan',version,description:codexEnabled?'回看工作台（含暂存 Codex 适配）':'回看 · DeepSeek Harness',huikanIntegrations:{harness:true,codex:codexEnabled},author:'Huikan contributors',license:'MIT',main:'main.cjs',private:true}));
await import('./verify-build-profile.mjs');
console.log('回看工作台已构建。');
