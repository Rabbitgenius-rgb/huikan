import {readFile,mkdir,copyFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const outputDirectory=process.env.MENGCANG_RECALL_PLUGIN_OUTPUT || join(root,'dist');
await mkdir(outputDirectory,{recursive:true});
for(const file of ['host.js','core.js','schemas.js','topic-model.js'])await writeFile(join(outputDirectory,file),(await readFile(join(root,'src',file),'utf8')).replace("../../shared/harness-compatibility.cjs","./harness-compatibility.cjs"));
const compatibility=await readFile(join(root,'../shared/harness-compatibility.cjs'),'utf8');
await writeFile(join(outputDirectory,'harness-compatibility.cjs'),compatibility);
await copyFile(join(root,'../shared/private-files.cjs'),join(outputDirectory,'private-files.cjs'));
await copyFile(join(root,'../shared/private-rpc.cjs'),join(outputDirectory,'private-rpc.cjs'));
await copyFile(join(root,'../shared/topic-contract.cjs'),join(outputDirectory,'topic-contract.cjs'));
await copyFile(join(root,'../shared/connection-discovery.cjs'),join(outputDirectory,'connection-discovery.cjs'));
const sources=await Promise.all(['core.js','focus.js','dom.js','client.js'].map(file=>readFile(join(root,'src',file),'utf8')));
const body=sources.join('\n').replace(/^import harnessCompatibility from .*;\n/m,'').replace(/^export /gm,'');
const output=`// Harness compatibility is checked through public APIs and message markup.\nwindow.__ModuleLoader__.load({id:'@mengcang/harness-recall',factory(require){\nconst harnessCompatibility=(()=>{const module={exports:{}};\n${compatibility}\nreturn module.exports;})();\n${body}\nreturn createClient(require('react'));\n}});\n`;
new Function(output);
await writeFile(join(outputDirectory,'client.js'),output);
console.log('Built standalone Host and Client entrypoints.');
